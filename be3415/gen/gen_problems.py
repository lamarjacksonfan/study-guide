import json, os, sys
G = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1]

def tsv(name):
    rows = []
    for line in open(os.path.join(G, name)):
        line = line.rstrip('\n')
        if line:
            rows.append(line.split('\t'))
    return rows

enz = [[n, s, int(c)] for n, s, c in tsv('enz.tsv')]
plic = sorted([[n.rstrip('2'), int(p)] for n, p in tsv('plic.tsv')], key=lambda r: r[1])
pet = sorted([[n, int(p)] for n, p in tsv('pet.tsv')], key=lambda r: r[1])

L = []
w = L.append
w("// Problem-generator source data: enzyme sites, plasmid maps, fixed problems.")
w("// Generated by scratchpad/gen/gen_problems.py. Positions verified against the")
w("// professor's gel answer key (SapI+HpaI -> 1985/3777; SspI+BamHI -> 514/5248).")
w("window.BE = window.BE || {};")
w("")
w("// [name, recognition site 5'->3' on the top strand, bases before the cut]")
w("// Every site is a palindrome, so the bottom strand is cut at (length - cut).")
w("BE.enzymes = [")
for n, s, c in enz:
    w('  ["%s", "%s", %d],' % (n, s, c))
w("];")
w("")
w("// Circular maps: [enzyme, position]. A single cut gives one full-length linear band.")
w("BE.plasmids = {")
for key, title, size, rows, note in [
    ("plic", "pLICHIS_Stag", 5762, plic,
     "The plasmid on the last page of the review. lacI, AmpR and pBR322ori."),
    ("pet", "pET22b-T5-sfGFP", 8577, pet,
     "The Lab 6 plasmid. AmpR near 900; superfolder GFP spans about 5330-5990."),
]:
    w('  %s: { name: "%s", size: %d, note: "%s", sites: [' % (key, title, size, note))
    for i in range(0, len(rows), 4):
        chunk = rows[i:i + 4]
        w('    ' + ' '.join('["%s", %d],' % (n, p) for n, p in chunk))
    w("  ] },")
w("};")
open(OUT, 'w').write('\n'.join(L) + '\n')
print("wrote", OUT, len(L), "lines")
